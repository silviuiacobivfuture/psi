/**
 * The shape of the long-form pages: which message keys exist for each. The text itself lives in
 * messages/content/{ro,en}.json under `<page>_<section>_h`, `_p<n>`, `_l<n>` (and `_n` for a
 * glossary term's name); the page tests fail when a key here has no message in either language.
 */
export interface SectionSpec {
	readonly id: string;
	/** Paragraphs: `_p1`.. */
	readonly p: number;
	/** List items: `_l1`.. */
	readonly l: number;
	/** How many of the list items link out (the page's SOURCE_LINKS, in order). */
	readonly links: number;
	/** A glossary term: has a `_n` name. */
	readonly named: boolean;
}

