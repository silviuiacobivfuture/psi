import {
	allAppRelations,
	appRelations,
	CATALOGUE,
	type PermissionDef,
	parseRelation,
} from "./catalogue";
import { ACTION_LABEL, GROUP_LABEL, RESOURCE_LABEL } from "./labels";
import { buildModel, type Clause, PLATFORM_CLAUSE, render } from "./model";

type Label = { ro: string; en: string };

export function labelOf(def: Pick<PermissionDef, "resource" | "action" | "group">): Label {
	const r = RESOURCE_LABEL[def.resource] ?? { ro: def.resource, en: def.resource };
	const a = ACTION_LABEL[def.action] ?? { ro: def.action, en: def.action };
	const g = def.group === undefined ? undefined : GROUP_LABEL[def.group];
	return {
		ro: `${r.ro}: ${a.ro}${g === undefined ? "" : ` (${g.ro})`}`,
		en: `${r.en}: ${a.en}${g === undefined ? "" : ` (${g.en})`}`,
	};
}

/** The role the estate's platform administrators hold: it manages apps, members and roles, never clinical content. */
const PLATFORM_ADMIN_GRANTS = CATALOGUE.filter((def) => def.platformAdmin === true).flatMap((def) =>
	appRelations(def).map((relation) => `sched_app#${relation}`),
);

/** The manifest for Polaris's generator (SEB authz/manifest.schema.json), rendered from the catalogue and the model. */
export function buildManifest(): Record<string, unknown> {
	const features = [...new Set(CATALOGUE.map((d) => d.resource))].map((resource) => ({
		key: resource,
		name: RESOURCE_LABEL[resource] ?? { ro: resource, en: resource },
		permissions: CATALOGUE.filter((d) => d.resource === resource).map((def) => ({
			key: def.key,
			name: labelOf(def),
			grants: appRelations(def).map((relation) => `sched_app#${relation}`),
			effect: def.effect,
		})),
	}));
	const platformRoleClause = render(PLATFORM_CLAUSE);
	const objects = Object.entries(buildModel()).map(([type, relations]) => ({
		type,
		scope:
			type === "sched_app"
				? { scope_type: "platform", relation: "parent_platform" }
				: { scope_type: "sched_app", relation: "app" },
		relations: Object.entries(relations).map(([name, clauses]) => ({
			name,
			// The role clause is the generator's to append (a catalogue role grants the relation), so it is not written here.
			from: clauses.filter((c: Clause) => render(c) !== platformRoleClause).map(render),
		})),
	}));
	return {
		$comment:
			"psi's scheduling service (apps/scheduling-api). GENERATED by `pnpm --filter @psi/scheduling-api authz:gen` from src/authz/catalogue.ts and src/authz/model.ts: do not edit. Per app, roles are DATA: a role is a sched_role object whose members hold the permission relations through `sched_role#member` tuples the service writes; the catalog role below is only the estate administrators' (apps, members, roles).",
		app: "scheduling-api",
		module: "sched",
		generated_dir: "src/authz",
		version: 1,
		features,
		objects,
		roles: [
			{
				key: "sched:app_admin",
				name: { ro: "Administrator programări", en: "Scheduling administrator" },
				description: {
					ro: "Creează aplicații, gestionează echipa, rolurile și setările lor; nu citește date clinice.",
					en: "Creates apps and manages their team, roles and settings; reads no clinical data.",
				},
				scope_type: "platform",
				grants: PLATFORM_ADMIN_GRANTS,
				assignable: true,
				max_duration: null,
			},
		],
		group_bindings: [],
		providers: {
			identity: { supported: ["authentik"], selected: "authentik" },
			authorization: { supported: ["autorizare"], selected: "autorizare" },
		},
		public_reasons: [
			{
				key: "health_probe",
				description: {
					ro: "/health răspunde fără date, pentru sondele kubelet.",
					en: "/health answers with no data, for the kubelet's probes.",
				},
			},
			{
				key: "openapi_document",
				description: {
					ro: "/v1/openapi.json este contractul public al serviciului; nu returnează date.",
					en: "/v1/openapi.json is the service's public contract; it returns no data.",
				},
			},
		],
	};
}

/** A guard for the generator's own input: every relation a feature grants exists on sched_app. */
export function grantedRelationsExist(): boolean {
	return allAppRelations().every((relation) => parseRelation(relation) !== undefined);
}
