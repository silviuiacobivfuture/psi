import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

/**
 * The identity of the Convex functions this package deploys: a SHA-256 over every source the functions are built from
 * (convex/, the src/ they import; never _generated, tests or this hash's own file). scheduling-api is built with the
 * same constant and is not ready until the deployment answers it (convex/deployment.ts), so a service never calls a
 * function that is not deployed yet. A version number cannot say this: two branches merged land on the same one.
 *
 *   pnpm --filter @psi/scheduling functions-hash          writes src/functions-hash.generated.ts
 *   functionsHash() / HASH_FILE                            what the guard test (functions-hash.test.ts) compares
 */
const PKG = join(import.meta.dirname, "..");
export const HASH_FILE = join(PKG, "src/functions-hash.generated.ts");

function sources(dir: string): string[] {
	return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const path = join(dir, entry.name);
		if (entry.isDirectory())
			return entry.name === "_generated" || entry.name === "test" ? [] : sources(path);
		const counted =
			entry.name.endsWith(".ts") && !entry.name.endsWith(".test.ts") && path !== HASH_FILE;
		return counted ? [path] : [];
	});
}

export function functionsHash(): string {
	const hash = createHash("sha256");
	for (const path of [...sources(join(PKG, "convex")), ...sources(join(PKG, "src"))].sort()) {
		hash.update(relative(PKG, path));
		hash.update("\u0000");
		hash.update(readFileSync(path));
		hash.update("\u0000");
	}
	return hash.digest("hex").slice(0, 16);
}

export function hashFileText(hash: string): string {
	return [
		"// Generated by scripts/functions-hash.ts (pnpm --filter @psi/scheduling functions-hash). Do not edit.",
		"/** The identity of the Convex functions built from this commit's sources (see scripts/functions-hash.ts). */",
		`export const FUNCTIONS_HASH = "${hash}";`,
		"",
	].join("\n");
}

if (process.argv[1] === import.meta.filename) {
	writeFileSync(HASH_FILE, hashFileText(functionsHash()));
	console.log(`functions hash ${functionsHash()} written to ${relative(PKG, HASH_FILE)}`);
}
