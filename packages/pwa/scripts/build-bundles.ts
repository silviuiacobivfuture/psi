/**
 * Bundles the service worker (src/worker/sw.ts) and the page client (src/client/client.ts) into
 * src/bundles.generated.ts as strings, so an app's server bundle carries them with no file to
 * find at run time. `--check` fails when the committed file is out of date (CI, and a test).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const OUT = `${ROOT}src/bundles.generated.ts`;

async function bundle(entry: string): Promise<string> {
	const result = await build({
		entryPoints: [`${ROOT}${entry}`],
		bundle: true,
		write: false,
		format: "iife",
		target: ["chrome109", "safari16", "firefox115"],
		minify: true,
		legalComments: "none",
	});
	const file = result.outputFiles[0];
	if (file === undefined) throw new Error(`esbuild produced nothing for ${entry}`);
	return file.text.trim();
}

const worker = await bundle("src/worker/sw.ts");
const client = await bundle("src/client/client.ts");
const text = `// GENERATED by scripts/build-bundles.ts from src/worker/sw.ts and src/client/client.ts — run \`pnpm --filter @psi/pwa build\`, never edit.
/** The service worker's code; the server prepends \`self.__PSI_PWA__ = …;\`. */
export const WORKER_JS: string = ${JSON.stringify(worker)};
/** The page client, served hashed under /assets/pwa/. */
export const CLIENT_JS: string = ${JSON.stringify(client)};
`;

if (process.argv.includes("--check")) {
	const committed = readFileSync(OUT, "utf8");
	if (committed !== text) {
		console.error("src/bundles.generated.ts is out of date: run `pnpm --filter @psi/pwa build`");
		process.exit(1);
	}
	console.log("bundles up to date");
} else {
	writeFileSync(OUT, text);
	console.log(`worker ${worker.length} B, client ${client.length} B → src/bundles.generated.ts`);
}
