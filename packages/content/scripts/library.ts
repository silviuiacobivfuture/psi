/**
 * The article library under src/articles/library/<brand>/<slug>.ts: one file per article, each
 * `export const article: ArticleInput = { … }`.
 *
 *     pnpm --filter @psi/content exec tsx scripts/library.ts check [file…]   # validate (default: all)
 *     pnpm --filter @psi/content exec tsx scripts/library.ts index           # write library/index.generated.ts
 *
 * `check` enforces the house shape from docs/brands/writing-voice.md on top of the schema.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { Article, wordCount } from "../src/schema";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../src/articles/library");
const BRANDS = ["psizone", "eqsync", "hemisync"] as const;

function allFiles(): string[] {
	return BRANDS.flatMap((b) =>
		readdirSync(join(ROOT, b))
			.filter((f) => f.endsWith(".ts"))
			.sort()
			.map((f) => join(ROOT, b, f)),
	);
}

async function fixedSlugs(): Promise<Set<string>> {
	const { ARTICLES } = await import("../src/articles/catalogue");
	const { LIBRARY } = await import("../src/articles/library/index.generated");
	const library = new Set(LIBRARY.map((a) => a.slug));
	return new Set(
		ARTICLES.filter((a) => a.status !== "in-review" && !library.has(a.slug)).map((a) => a.slug),
	);
}

/** Everything wrong with one library file (empty = it may ship). */
async function problemsOf(file: string, fixed: Set<string>): Promise<string[]> {
	const problems: string[] = [];
	try {
		const mod = (await import(pathToFileURL(resolve(file)).href)) as { article?: unknown };
		const parsed = Article.safeParse(mod.article);
		if (!parsed.success) {
			return parsed.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`);
		}
		const a = parsed.data;
		const brandDir = basename(dirname(resolve(file)));
		if (a.slug !== basename(file, ".ts")) problems.push(`slug "${a.slug}" ≠ file name`);
		if (a.brand !== brandDir) problems.push(`brand "${a.brand}" ≠ folder "${brandDir}"`);
		if (fixed.has(a.slug)) problems.push(`slug "${a.slug}" already used by a hand-written article`);
		if (a.status !== "draft") {
			problems.push("status must be draft (a person publishes)");
			return problems;
		}
		if (!a.aiDrafted) problems.push("aiDrafted must be true");
		if (a.seo === null) problems.push("seo is required");
		if (a.faq.length < 4) problems.push(`faq has ${a.faq.length}, needs 4–8`);
		if (a.sources.length < 3) problems.push(`sources has ${a.sources.length}, needs ≥ 3`);
		for (const loc of ["ro", "en"] as const) {
			const words = a.body.reduce(
				(n, b) =>
					n +
					(b.type === "list"
						? b.items.reduce((k, i) => k + wordCount(i[loc]), 0)
						: wordCount(b.text[loc])),
				0,
			);
			if (words < 1200) problems.push(`${loc} body is ${words} words, needs ≥ 1200`);
			for (const q of a.faq) {
				const w = wordCount(q.a[loc]);
				if (w < 30 || w > 140) problems.push(`${loc} faq answer is ${w} words (30–140)`);
			}
		}
		const h2 = a.body.filter((b) => b.type === "h2").length;
		if (h2 < 5 || h2 > 10) problems.push(`${h2} h2 sections, needs 5–10`);
		if (!a.body.some((b) => b.type === "list")) problems.push("needs at least one list");
		const ro = JSON.stringify(
			a.body.map((b) => (b.type === "list" ? b.items.map((i) => i.ro) : b.text.ro)),
		);
		if (/[şţŞŢ]/.test(ro + a.title.ro + a.standfirst.ro))
			problems.push("Romanian uses cedilla ş/ţ: use comma-below ș/ț");
	} catch (e) {
		problems.push(`does not load: ${e instanceof Error ? e.message : String(e)}`);
	}
	return problems;
}

async function check(files: string[]): Promise<number> {
	const fixed = await fixedSlugs();
	let bad = 0;
	for (const file of files) {
		const problems = await problemsOf(file, fixed);
		const rel = relative(process.cwd(), file);
		if (problems.length > 0) {
			bad++;
			console.log(`✗ ${rel}\n  - ${problems.join("\n  - ")}`);
		} else console.log(`✓ ${rel}`);
	}
	console.log(`${files.length - bad}/${files.length} ok`);
	return bad;
}

/** Writes the index of the files that pass `check` (a half-written file never reaches a site). */
async function index(): Promise<void> {
	const fixed = await fixedSlugs();
	const files: string[] = [];
	for (const f of allFiles()) if ((await problemsOf(f, fixed)).length === 0) files.push(f);
	const lines = files.map((f, i) => {
		const spec = `./${relative(ROOT, f).replace(/\.ts$/, "")}`;
		return `import { article as a${i} } from "${spec}";`;
	});
	const body = [
		"// Generated by `tsx scripts/library.ts index` — do not edit by hand.",
		'import type { ArticleInput } from "../../schema";',
		...lines,
		"",
		"export const LIBRARY: ReadonlyArray<ArticleInput> = [",
		...files.map((_, i) => `\ta${i},`),
		"];",
		"",
	].join("\n");
	writeFileSync(join(ROOT, "index.generated.ts"), body);
	console.log(`index: ${files.length} of ${allFiles().length} articles pass`);
}

const [cmd = "check", ...rest] = process.argv.slice(2);
if (cmd === "index") await index();
else process.exit((await check(rest.length > 0 ? rest : allFiles())) > 0 ? 1 : 0);
