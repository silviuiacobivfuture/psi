import ts from "typescript";

/**
 * Compiles the compass chat's page script (src/client/compass-chat.ts) to the plain JavaScript the
 * compass inlines: types stripped, wrapped in a function so nothing leaks to the page's globals
 * but `window.psiChat`. Shared by the build script and the test that keeps the output current.
 */
function compileClient(source: string): string {
	const out = ts.transpileModule(source, {
		compilerOptions: {
			target: ts.ScriptTarget.ES2020,
			module: ts.ModuleKind.ESNext,
			removeComments: true,
		},
	}).outputText;
	const body = out.replace(/^export \{\};\s*$/m, "").trim();
	return `(() => {\n${body}\n})();`;
}

/** The page scripts, in the order they run: the capsule's field, keyboard and handle, the chat's store, the invitation, then the full screen. */
export const CLIENT_SOURCES = [
	"compass-capsule.ts",
	"compass-chat.ts",
	"compass-invite.ts",
	"compass-fullscreen.ts",
] as const;

/** Every page script compiled, one function each, as the one script the compass inlines. */
export function compileClients(sources: ReadonlyArray<string>): string {
	return sources.map(compileClient).join("\n");
}

/** The one script a capsule that is not the guide's compass inlines: the shared field and the full screen, without the guide's conversation store (the admin's assistant). */
export const CAPSULE_SOURCES = ["compass-capsule.ts", "compass-fullscreen.ts"] as const;

/** The generated module's text, as committed. */
export function generatedModule(js: string, capsuleJs: string): string {
	return `// GENERATED by scripts/build-client.ts from the page scripts in src/client (build.ts lists them) — run \`pnpm --filter @psi/ui build:client\`, never edit.
/** The compass's page script (the chat, the invitation and the full screen), inlined once per page inside the compass. */
export const COMPASS_CHAT_JS: string = ${JSON.stringify(js)};
/** The capsule without the guide: its field, keyboard and handle, and its full screen (client/compass-capsule.ts and compass-fullscreen.ts). */
export const CAPSULE_FULLSCREEN_JS: string = ${JSON.stringify(capsuleJs)};
`;
}
