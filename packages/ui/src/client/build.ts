import ts from "typescript";

/**
 * Compiles the compass chat's page script (src/client/compass-chat.ts) to the plain JavaScript the
 * compass inlines: types stripped, wrapped in a function so nothing leaks to the page's globals
 * but `window.psiChat`. Shared by the build script and the test that keeps the output current.
 */
function compileClient(source: string): string {
	const out = ts.transpileModule(source, {
		compilerOptions: {
			target: ts.ScriptTarget.ES2020,
			module: ts.ModuleKind.ESNext,
			removeComments: true,
		},
	}).outputText;
	const body = out.replace(/^export \{\};\s*$/m, "").trim();
	return `(() => {\n${body}\n})();`;
}

/** The page scripts, in the order they run: the chat's store, then the invitation. */
export const CLIENT_SOURCES = ["compass-chat.ts", "compass-invite.ts"] as const;

/** Every page script compiled, one function each, as the one script the compass inlines. */
export function compileClients(sources: ReadonlyArray<string>): string {
	return sources.map(compileClient).join("\n");
}

/** The generated module's text, as committed. */
export function generatedModule(js: string): string {
	return `// GENERATED by scripts/build-client.ts from src/client/compass-chat.ts and compass-invite.ts — run \`pnpm --filter @psi/ui build:client\`, never edit.
/** The compass's page script (the chat and the invitation), inlined once per page inside the compass. */
export const COMPASS_CHAT_JS: string = ${JSON.stringify(js)};
`;
}
