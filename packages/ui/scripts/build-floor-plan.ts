/**
 * Bundles the floor plan's page script (src/floor-plan/client/main.ts and the pure modules it shares
 * with the server and the tests) into src/floor-plan/client.generated.ts. `--check` fails when the
 * committed file is out of date.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const OUT = `${ROOT}src/floor-plan/client.generated.ts`;

const result = await build({
	entryPoints: [`${ROOT}src/floor-plan/client/main.ts`],
	bundle: true,
	write: false,
	format: "iife",
	target: "es2020",
	minify: true,
	legalComments: "none",
	logLevel: "silent",
});
const js = result.outputFiles[0]?.text.trim() ?? "";
if (js === "" || js.includes("</script"))
	throw new Error("the floor plan bundle is empty or closes a script tag");
const text = `// GENERATED by scripts/build-floor-plan.ts from src/floor-plan/client/main.ts — run \`pnpm --filter @psi/ui build:client\`, never edit.
/** The floor plan's page script, inlined once per plan. */
export const FLOOR_PLAN_JS: string = ${JSON.stringify(js)};
`;

if (process.argv.includes("--check")) {
	if (readFileSync(OUT, "utf8") !== text) {
		console.error("client.generated.ts is out of date: run `pnpm --filter @psi/ui build:client`");
		process.exit(1);
	}
	console.log("floor plan bundle up to date");
} else {
	writeFileSync(OUT, text);
	console.log(`floor plan ${js.length} B → src/floor-plan/client.generated.ts`);
}
