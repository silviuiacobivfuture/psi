function catalog<
	const G extends string,
	E extends z.ZodObject,
	C extends z.ZodObject,
	P extends z.ZodObject,
>(
	group: G,
	seg: string,
	entity: E,
	create: C,
	patch: P,
	label: string,
	resource: string = group,
	/** People are calendars (the object a person's scopes are resolved on); everything else is app-wide. */
	object?: SchedType,
	removal = "delete",
) {
	const on = (list: boolean): Target =>
		object === undefined
			? { kind: "app" }
			: list
				? { kind: "list", type: object }
				: { kind: "object", type: object };
	return [
		route({
			id: `${group}.list` as const,
			method: "GET",
			path: `/v1/apps/:app/${seg}`,
			side: "team",
			summary: `The app's ${label}`,
			params: AppParam,
			query: PageQuery,
			response: page(entity),
			permission: { key: `${resource}_view`, target: on(true) },
		}),
		route({
			id: `${group}.create` as const,
			method: "POST",
			path: `/v1/apps/:app/${seg}`,
			side: "team",
			summary: `Add ${label}`,
			params: AppParam,
			body: create,
			response: entity,
			permission: { key: `${resource}_create`, target: { kind: "app" } },
			audit: `${group}.create`,
		}),
		route({
			id: `${group}.update` as const,
			method: "PATCH",
			path: `/v1/apps/:app/${seg}/:id`,
			side: "team",
			summary: `Change ${label}`,
			params: IdParam,
			body: patch,
			response: entity,
			permission: { key: `${resource}_edit`, target: on(false) },
			audit: `${group}.update`,
		}),
		route({
			id: `${group}.remove` as const,
			method: "DELETE",
			path: `/v1/apps/:app/${seg}/:id`,
			side: "team",
			summary: `Remove ${label} (deactivates when it has history)`,
			params: IdParam,
			response: Ok,
			permission: { key: `${resource}_${removal}`, target: on(false) },
			audit: `${group}.delete`,
		}),
	] as const;
}

