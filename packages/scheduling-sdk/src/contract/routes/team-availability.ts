import { z } from "zod/v4";
import { route } from "../define";
import {
	Availability,
	AvailabilityPreview,
	AvailabilityPreviewQuery,
	AvailabilityRulesPut,
	OneOffCreate,
	OneOffCreated,
	RoomClosure,
	RoomClosureCreate,
	RulesCopied,
	RulesCopy,
} from "../entities-availability";
