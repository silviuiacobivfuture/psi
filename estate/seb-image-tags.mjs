#!/usr/bin/env node
// The image tags of the images the estate builds (e.g. estate-front, autorizare-svc), for the SEB
// pieces that run them FROM THE BUNDLE. The tag lives in the estate's component (estate/seb-components/<piece>/
// kustomization.yaml, `images: [{name: WLREGISTRY/WLAPPS/<repo>, newTag}]`): CI writes it there,
// the next bundle is built from it, and — so a CI build deploys without a new bundle — the
// generated Application sets it too, in spec.source.kustomize.images (the bundle ships such a piece
// as a kustomization: SEB tools/bundle/estate-images.mjs, bundle.json `estateImages`).
//
//   node estate/seb-image-tags.mjs                       check: every switched piece's Application
//                                                        names its component's tag (exit 1 if not)
//   node estate/seb-image-tags.mjs --write               the same, then rewrite the Applications' tags
//   node estate/seb-image-tags.mjs --emit <id> <name>…   the kustomize.images block for piece <id>
//                                                        (estate/seb-upgrade.sh writes it)
//   --apps-dir <dir>  (default: estate/seb-upgrade.conf's apps-dir for the first of the identity's
//                     ENVIRONMENTS, where estate/seb-upgrade.sh writes them)
//   --piece <id>      (repeatable) only those pieces' Applications: a deploy step checks and
//                     writes the pieces whose image IT built, so another piece's bundle never
//                     fails it (e.g. autorizare + openfga for the autorizare-svc build)
//   SEB_ESTATE_COMPONENTS overrides estate/seb-components (the gate only)
//
// No dependency but Node (CI's deploy step runs it with no install): it reads the component's
// `images:` entries and the generated Application's lines (estate/seb-upgrade.sh writes them) as text.
//
// REFUSED, writing nothing, by name: a generated Application whose piece's component pins an image
// the estate builds but which sets no tag for it — it runs from a bundle that cannot take one, so a CI
// build would be pushed and NOT deployed (release a bundle whose piece carries estateImages); a
// component naming no tag for an image the Application sets.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const MARK = "# GENERATED by estate/seb-upgrade.sh";
const COMPONENTS = process.env.SEB_ESTATE_COMPONENTS ?? join(ROOT, "estate/seb-components");

/** `- name: WLREGISTRY/WLAPPS/<repo>` then its `newTag:` (quoted or not), as the component writes them. */
const COMPONENT_IMAGE =
	/^\s*-\s*name:\s*"?WLREGISTRY\/WLAPPS\/([A-Za-z0-9._-]+)"?\s*\n\s*newTag:\s*"?([A-Za-z0-9._-]+)"?\s*$/gm;
/** The generated Application's kustomize.images entries: `        - <name>:<tag>`. */
const APP_IMAGE = /^ {8}- (\S+):([A-Za-z0-9._-]+)$/gm;

/**
 * Where estate/seb-upgrade.sh writes the first environment's Applications: estate/seb-upgrade.conf
 * `apps-dir` with {env} the first of estate/identity.yaml's ENVIRONMENTS. Refused (exit 1) when
 * either is not declared: there is no default.
 * @returns {string}
 */
function defaultAppsDir() {
	/** @param {string} f @param {string} key @param {RegExp} re @returns {string} */
	const one = (f, key, re) => {
		const p = join(ROOT, f);
		const m = existsSync(p) ? [...readFileSync(p, "utf8").matchAll(re)] : [];
		const v = m.length === 1 ? (m[0]?.[1] ?? "") : "";
		if (v === "") {
			process.stderr.write(`REFUSED: ${f} must name ${key} exactly once (or pass --apps-dir)\n`);
			process.exit(1);
		}
		return v;
	};
	const pattern = one(
		"estate/seb-upgrade.conf",
		"apps-dir",
		/^apps-dir[ \t]*=[ \t]*(\S+)[ \t]*$/gm,
	);
	const env = one("estate/identity.yaml", "ENVIRONMENTS", /^ENVIRONMENTS:[ \t]*([a-z]+)/gm);
	return join(ROOT, pattern.replaceAll("{env}", env));
}

/**
 * The tags piece <id>'s component pins for the images the estate builds: repository (last segment) → tag.
 * @param {string} id @returns {Map<string, string>}
 */
export function componentTags(id) {
	const f = join(COMPONENTS, id, "kustomization.yaml");
	const tags = new Map();
	if (!existsSync(f)) return tags;
	for (const m of readFileSync(f, "utf8").matchAll(COMPONENT_IMAGE))
		tags.set(m[1] ?? "", m[2] ?? "");
	return tags;
}

/**
 * The kustomize.images block (indented for spec.source) for piece <id>'s rendered image names.
 * @param {string} id @param {string[]} names @returns {{ ok: true, text: string } | { ok: false, error: string }}
 */
export function emit(id, names) {
	const tags = componentTags(id);
	const lines = ["    kustomize:", "      images:"];
	for (const n of names) {
		const tag = tags.get(n.split("/").pop() ?? "");
		if (tag === undefined)
			return {
				ok: false,
				error: `piece ${id}: its component names no tag for ${n} (estate/seb-components/${id})`,
			};
		lines.push(`        - ${n}:${tag}`);
	}
	return { ok: true, text: `${lines.join("\n")}\n` };
}

/**
 * Check (and with write, fix) every generated Application in <apps> (only <pieces>' when given).
 * @param {string} apps @param {boolean} write @param {string[]} [pieces]
 * @returns {{ errors: string[], changes: string[] }}
 */
export function sync(apps, write, pieces = []) {
	const errors = [];
	const changes = [];
	/** @type {Array<[string, string]>} */
	const out = [];
	for (const f of readdirSync(apps)
		.filter((n) => /^seb-.+\.yaml$/.test(n))
		.sort()) {
		const file = join(apps, f);
		let text = readFileSync(file, "utf8");
		if (!text.startsWith(MARK)) continue;
		const id = /^ {4}path: pieces\/([a-z0-9_-]+)$/m.exec(text)?.[1] ?? "";
		if (pieces.length > 0 && !pieces.includes(id)) continue;
		const tags = componentTags(id);
		if (tags.size === 0) continue;
		const block = /^ {4}kustomize:\n {6}images:\n((?: {8}- .+\n)+)/m.exec(text)?.[1] ?? "";
		const entries = [...block.matchAll(APP_IMAGE)].map((m) => `${m[1]}:${m[2]}`);
		for (const repo of tags.keys())
			if (!entries.some((e) => e.split(":")[0]?.endsWith(`/${repo}`)))
				errors.push(
					`${f}: piece ${id} runs from a bundle that takes no tag for ${repo} (no spec.source.kustomize.images) — a CI build of ${repo} would be pushed and NOT deployed; release a bundle whose piece ${id} carries estateImages, then re-run estate/seb-upgrade.sh`,
				);
		for (const e of entries) {
			const i = e.lastIndexOf(":");
			const name = e.slice(0, i);
			const tag = tags.get(name.split("/").pop() ?? "");
			if (tag === undefined) {
				errors.push(`${f}: sets ${name}, for which estate/seb-components/${id} names no tag`);
				continue;
			}
			if (e.slice(i + 1) === tag) continue;
			changes.push(`${f}: ${e} → ${name}:${tag}`);
			text = text.replace(`        - ${e}\n`, `        - ${name}:${tag}\n`);
		}
		out.push([file, text]);
	}
	if (write && errors.length === 0) for (const [file, text] of out) writeFileSync(file, text);
	return { errors, changes };
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const argv = process.argv.slice(2);
	if (argv[0] === "--emit") {
		const [, id, ...names] = argv;
		const r = id ? emit(id, names) : { ok: false, error: "usage: --emit <id> <name>…" };
		if (!r.ok) {
			process.stderr.write(`REFUSED: ${r.error}\n`);
			process.exit(1);
		}
		process.stdout.write(r.text);
		process.exit(0);
	}
	const write = argv.includes("--write");
	const i = argv.indexOf("--apps-dir");
	const apps = i >= 0 && argv[i + 1] ? argv[i + 1] : defaultAppsDir();
	/** @type {string[]} */
	const pieces = [];
	argv.forEach((a, n) => {
		if (a === "--piece" && argv[n + 1]) pieces.push(argv[n + 1] ?? "");
	});
	const r = sync(apps, write, pieces);
	for (const c of r.changes)
		console.log(`${write && r.errors.length === 0 ? "wrote" : "differs"} ${c}`);
	if (r.errors.length) {
		for (const e of r.errors) console.error(`REFUSED: ${e}`);
		process.exit(1);
	}
	if (!write && r.changes.length) process.exit(1);
	console.log(
		`ok: every switched piece's Application names its component's tags${write ? ` (${r.changes.length} written)` : ""}`,
	);
}
