// An IMAGE-FIRST HOLD on a generated Application: the one line both ends of the hold read.
//
// A release that changes a piece's config together with the code of an image the estate builds
// declares `Take-Needs: image-first=<piece>` (SEB tools/release/take-needs.mjs). The take then keeps
// that piece's Application on the previous bundle while the estate's image is not yet built from the
// release (SEB tools/estate/image-first.mjs decides; estate/seb-upgrade.sh writes this line into the
// Application, right under its GENERATED mark), and the estate's pin — estate/seb-image-tags.mjs
// --write, run when CI pins the new build — moves the Application to the locked bundle AND the new
// tag in one commit. So the new config never runs on the old image (19 Nov: Polaris crash-looped on
// a WEBHOOK_EGRESS_* form its 0.1.197 image refuses), nor the old config on the new image.
//
//   # HELD image-first: moves to bundle <version> @ sha256:<64 hex> once <repo>[,<repo>] is built from <40-hex commit>[; after <piece>[,<piece>]]
//
// `after`: pieces the same release orders before this one (order=<first> before <piece>); the pin
// moves the held piece only once each of them is at the new bundle. Dependency-free.

export const HOLD_PREFIX = "# HELD image-first: ";
const HOLD =
	/^# HELD image-first: moves to bundle (\S+) @ (sha256:[0-9a-f]{64}) once ([A-Za-z0-9._,-]+) is built from ([0-9a-f]{40})(?:; after ([a-z0-9_,-]+))?$/m;
const SEB_TAG = /^seb-([0-9a-f]{7,40})(?:-[0-9A-Za-z._-]+)?$/;

/**
 * @typedef {{ version: string, digest: string, repos: string[], commit: string, after: string[] }} Hold
 */

/** The marker line for a hold. @param {Hold} h @returns {string} */
export function holdLine(h) {
	const after = h.after.length ? `; after ${h.after.join(",")}` : "";
	return `${HOLD_PREFIX}moves to bundle ${h.version} @ ${h.digest} once ${h.repos.join(",")} is built from ${h.commit}${after}`;
}

/**
 * The hold an Application carries: none, one, or a line that starts like one and does not parse.
 * @param {string} text @returns {{ held: false } | { held: true, hold: Hold } | { held: true, error: string }}
 */
export function parseHold(text) {
	if (!text.includes(HOLD_PREFIX)) return { held: false };
	const m = HOLD.exec(text);
	if (!m?.[1] || !m[2] || !m[3] || !m[4])
		return { held: true, error: `an image-first hold line that does not parse (${HOLD_PREFIX}…)` };
	return {
		held: true,
		hold: {
			version: m[1],
			digest: m[2],
			repos: m[3].split(",").filter(Boolean),
			commit: m[4],
			after: (m[5] ?? "").split(",").filter(Boolean),
		},
	};
}

/** Whether a pin (`<tag>` or `<tag>@sha256:…`) is a SEB build at all. @param {string} pin @returns {boolean} */
export const sebBuild = (pin) => SEB_TAG.test(pin.split("@")[0] ?? "");

/**
 * Whether a pin (`<tag>` or `<tag>@sha256:…`) is a SEB build of <commit>: seb-<hex>[-suffix] with
 * <hex> a prefix of it (the estate's tag form, SEB estate/seb-image-release.mjs).
 * @param {string} pin @param {string} commit @returns {boolean}
 */
export function builtFrom(pin, commit) {
	const m = SEB_TAG.exec(pin.split("@")[0] ?? "");
	return m?.[1] !== undefined && commit.startsWith(m[1]);
}

/**
 * Put the hold line under the GENERATED mark (replacing one already there).
 * @param {string} text @param {Hold} h @returns {string}
 */
export function withHold(text, h) {
	const lines = text.split("\n").filter((l) => !l.startsWith(HOLD_PREFIX));
	lines.splice(1, 0, holdLine(h));
	return lines.join("\n");
}

/**
 * The Application moved to the hold's bundle: every reference to its current digest (spec.info and
 * targetRevision) becomes the hold's, the GENERATED mark names the hold's version, the hold line goes.
 * @param {string} text @param {Hold} h @returns {{ ok: true, text: string } | { ok: false, error: string }}
 */
export function released(text, h) {
	const from = /^ {4}targetRevision: (sha256:[0-9a-f]{64})$/m.exec(text)?.[1];
	if (!from) return { ok: false, error: "names no targetRevision: sha256:… to move" };
	const out = text
		.split("\n")
		.filter((l) => !l.startsWith(HOLD_PREFIX))
		.join("\n")
		.replaceAll(from, h.digest)
		.replace(
			/^(# GENERATED by estate\/seb-upgrade\.sh from the locked bundle )\S+?\.( |$)/m,
			`$1${h.version}.$2`,
		);
	return { ok: true, text: out };
}
