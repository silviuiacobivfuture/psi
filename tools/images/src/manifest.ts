import type { Credit } from "./credits";
import type { Encoded, Format } from "./encode";
import { FORMATS } from "./encode";

export interface ManifestEntry {
	key: string;
	width: number;
	height: number;
	placeholder: string;
	files: ReadonlyArray<Encoded & { src: string }>;
}

function variants(entry: ManifestEntry, format: Format): string {
	const rows = entry.files
		.filter((f) => f.format === format)
		.sort((a, b) => a.width - b.width)
		.map((f) => `\t\t\t{ width: ${f.width}, src: "${f.src}" },`);
	return `\t\t${format}: [\n${rows.join("\n")}\n\t\t],`;
}

function creditSource(c: Credit): string {
	const q = (s: string) => JSON.stringify(s);
	return [
		"\t{",
		`\t\ttitle: ${q(c.title)},`,
		`\t\tauthor: ${q(c.author)},`,
		`\t\tsourceUrl: ${q(c.sourceUrl)},`,
		`\t\tlicence: ${q(c.licence)},`,
		`\t\tlicenceUrl: ${q(c.licenceUrl ?? c.sourceUrl)},`,
		`\t\tattributionRequired: ${c.attributionRequired},`,
		`\t\tmodifications: ${q(c.modifications)},`,
		"\t},",
	].join("\n");
}

/** The typed manifest one app imports: every image it shows, by key, and their credits. */
export function manifestSource(
	entries: ReadonlyArray<ManifestEntry>,
	credits: ReadonlyArray<Credit>,
): string {
	const body = [...entries]
		.sort((a, b) => a.key.localeCompare(b.key))
		.map((e) =>
			[
				`\t${e.key}: {`,
				`\t\twidth: ${e.width},`,
				`\t\theight: ${e.height},`,
				`\t\tplaceholder: "${e.placeholder}",`,
				...FORMATS.map((f) => variants(e, f)),
				"\t},",
			].join("\n"),
		)
		.join("\n");
	return [
		"// Generated by tools/images (`pnpm --filter @psi/images build`). Do not edit by hand.",
		"// Provenance and licences: packages/design/imagery/credits.json.",
		'import type { ImageAsset, ImageCredit } from "@psi/ui";',
		"",
		"export const IMAGES = {",
		body,
		"} as const satisfies Record<string, ImageAsset>;",
		"",
		"export type ImageKey = keyof typeof IMAGES;",
		"",
		"/** Where each image on this site comes from; the credits page lists them. */",
		"export const IMAGE_CREDITS: ReadonlyArray<ImageCredit> = [",
		...[...credits].sort((a, b) => a.name.localeCompare(b.name)).map(creditSource),
		"];",
		"",
	].join("\n");
}
