/*
 * The estate's script over PDFCraft — loaded by our nginx front from <head>, on
 * every page (gitops/services/pdfcraft/base/nginx.conf). Upstream is never
 * modified; this and recomex.css are the only things we put on their pages.
 *
 * 1. Their automatic "check for updates" asks GitHub, then two third-party
 *    GitHub mirrors, for upstream's releases — from every visitor's browser. It
 *    reads its switch from localStorage, so the switch is set OFF here, before
 *    their application starts. (The manual button is hidden by recomex.css.)
 * 2. The credit, „realizat cu PDFCraft”, the one place their name appears:
 *    a small link, bottom-right, to the project's page. Added AFTER their page
 *    has hydrated, outside anything their React tree renders, so it can never
 *    disturb it.
 *
 * Every string comes from packages/rmx-i18n (namespace `pdf`), spliced in below
 * by packages/rmx-ui/scripts/pdfcraft-theme.mjs; the drift test fails when they
 * differ. Failing quietly is the design: if anything here throws, their page is
 * exactly as upstream ships it.
 */
(() => {
	/* ── BEGIN GENERATED MESSAGES ── */
	// biome-ignore format: generated by packages/rmx-ui/scripts/pdfcraft-theme.mjs
	const MESSAGES = {"ro":{"pdf_credit":"realizat cu PDFCraft","pdf_credit_label":"Realizat cu PDFCraft — pagina proiectului pe GitHub, se deschide într-o filă nouă"},"en":{"pdf_credit":"made with PDFCraft","pdf_credit_label":"Made with PDFCraft — the project's page on GitHub, opens in a new tab"}};
	/* ── END GENERATED MESSAGES ── */

	const UPDATE_SETTINGS = "pdfcraft_update_settings";
	const PROJECT = "https://github.com/PDFCraftTool/pdfcraft";

	try {
		const raw = window.localStorage.getItem(UPDATE_SETTINGS);
		const settings = raw ? JSON.parse(raw) : {};
		if (settings === null || typeof settings !== "object" || settings.autoCheck !== false) {
			window.localStorage.setItem(
				UPDATE_SETTINGS,
				JSON.stringify({ ...(settings || {}), autoCheck: false }),
			);
		}
	} catch {
		/* storage blocked: the check runs as upstream ships it */
	}

	// The THEME, resolved the estate's way before the first paint. The estate's
	// bar (next-themes) and their pages share one key, `theme`, and one switch,
	// `dark` on <html>; but with no key yet their pages follow the system while
	// the estate defaults to dark, and they do not know "system" at all. Resolving
	// it here, from <head>, means the page is painted in the theme the bar will
	// show, instead of flashing the other one until the bar loads.
	try {
		const theme = window.localStorage.getItem("theme");
		const systemDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
		const dark = theme === null ? true : theme === "dark" || (theme === "system" && systemDark);
		document.documentElement.classList.toggle("dark", dark);
	} catch {
		/* storage blocked: their own script decides, as upstream ships it */
	}

	const locale = window.location.pathname.startsWith("/en/") ? "en" : "ro";
	const t = MESSAGES[locale] || MESSAGES.ro;

	function credit() {
		if (document.getElementById("recomex-credit")) return;
		const a = document.createElement("a");
		a.id = "recomex-credit";
		a.href = PROJECT;
		a.target = "_blank";
		a.rel = "noopener noreferrer";
		a.lang = locale;
		a.textContent = t.pdf_credit;
		a.setAttribute("aria-label", t.pdf_credit_label);
		document.body.appendChild(a);
	}

	// After their page has hydrated: `load` fires once every script has run.
	// Re-added if their router ever replaces the body's children.
	function start() {
		credit();
		new MutationObserver(credit).observe(document.body, { childList: true });
	}
	if (document.readyState === "complete") start();
	else window.addEventListener("load", start, { once: true });
})();
